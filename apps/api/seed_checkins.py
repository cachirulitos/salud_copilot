async def checkin(client: httpx.AsyncClient, name: str, phone: str, area_ids: list[str]) -> dict | None:
    # Pick 2-4 random areas (no repeats)
    n = random.randint(2, min(4, len(area_ids)))
    study_ids = random.sample(area_ids, n)

    payload = {
        "phone_number": phone,
        "clinic_id": CLINIC_ID,
        "study_ids": study_ids,
        "has_appointment": random.choice([True, False]),
        "is_urgent": random.random() < 0.15,
    }

    try:
        r = await client.post(f"{API_URL}/api/v1/visits/check-in", json=payload, timeout=15)
        if r.status_code in (200, 201):
            data = r.json()
            steps = ", ".join(s["area_name"] for s in data.get("sequence", []))
            print(f"  ✓ {name} → {steps} ({data['total_estimated_minutes']} min)")
            return data
        else:
            print(f"  ✗ {name}: HTTP {r.status_code} — {r.text[:120]}")
    except Exception as e:
        print(f"  ✗ {name}: {e}")
    return None


async def main():
    print(f"Checking in {len(PATIENTS)} patients against {API_URL}")
    print(f"Clinic: {CLINIC_ID}")
    print("Fetching areas from DB...")
    area_ids = await fetch_area_ids()
    if not area_ids:
        print("No active areas found — run seed_real_data.py first.")
        return
    print()

    async with httpx.AsyncClient() as client:
        for name, phone in PATIENTS:
            await checkin(client, name, phone, area_ids)
            await asyncio.sleep(0.3)

    print("\nDone. Refresh the doctor dashboard to see the queue.")


if __name__ == "__main__":
    asyncio.run(main())
