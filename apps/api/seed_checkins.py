"""
Bulk check-in script — seeds realistic patient visits for demo/testing.
Usage: python seed_checkins.py [--api http://localhost:8000]

Each patient gets 2-4 random studies. The script uses the real Culiacán clinic
UUIDs generated by seed_real_data.py (stable, deterministic UUIDs).
"""

import asyncio
