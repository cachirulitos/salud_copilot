from seed_real_data import get_stable_uuid  # noqa: E402

API_URL = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000"

CLINIC_ID = str(get_stable_uuid("clinic", 1))


async def fetch_area_ids() -> list[str]:
    from sqlalchemy import select
    from app.core.database import AsyncSessionLocal
    from app.models.models import ClinicalArea

    async with AsyncSessionLocal() as db:
        r = await db.execute(
            select(ClinicalArea).where(
                ClinicalArea.clinic_id == uuid.UUID(CLINIC_ID),
                ClinicalArea.active.is_(True),
            )
        )
        areas = r.scalars().all()
        for a in areas:
            print(f"  {a.name} ({a.study_type}): {a.id}")
        return [str(a.id) for a in areas]

